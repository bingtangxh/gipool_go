// cynoJoke displays random Cyno cold jokes until the user chooses to exit.
func cynoJoke() {
	idx := rand.Intn(len(jokes))
	for {
		joke := jokes[idx]
		cls()
		fmt.Println(joke.Question)
		fmt.Println()
		if joke.Answer != "" {
			fmt.Println("Press ENTER to see the answer...")
			getch()
			fmt.Println()
			fmt.Println(joke.Answer)
			fmt.Println()
		}

		fmt.Print("Press ENTER to continue, or any other key followed by ENTER to go back...")
		b := getch()
		if b != '\r' && b != '\n' {
			return
		}
		idx = rand.Intn(len(jokes))
	}
}
