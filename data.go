// makeUp 用参数里给的不定长度数字集合弄一个 [24]uint 的数组
func makeUp(ids ...uint) [24]uint {
	var arr [24]uint
	for i,v := range ids {
		if i >= 24 {
			break
		}
		arr[i] = v
	}
	return arr
}

